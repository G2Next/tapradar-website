  body text not null,
  target_type text not null default 'all' check (target_type in ('all','segment','individual')),
  segment_name text,
  moderation_status text not null default 'pending_review'
    check (moderation_status in ('pending_review','approved','rejected')),
  delivery_status text not null default 'awaiting_approval'
