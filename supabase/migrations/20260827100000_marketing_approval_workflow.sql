alter table public.offers add constraint offers_moderation_status_check
  check (moderation_status in ('pending_review', 'approved', 'rejected'));

update public.offers
set moderation_status = case when is_active then 'approved' else 'pending_review' end,
    requested_active = is_active,
    submitted_at = coalesce(submitted_at, created_at)
where submitted_at is null;

create table if not exists public.push_messages (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.organizations(id) on delete cascade,
  location_id uuid references public.locations(id) on delete set null,
  created_by uuid references auth.users(id) on delete set null,
