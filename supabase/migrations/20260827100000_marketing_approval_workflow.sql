  on public.admin_notifications (recipient_user_id, created_at desc) where read_at is null;

create or replace function public.queue_marketing_admin_notifications()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  organization_name text;
  kind_label text;
  target_title text;
  target_body text;
  target_href text := '/admin/marketing';
  organization_id_value uuid;
begin
  if tg_table_name = 'offers' then
    if new.moderation_status <> 'pending_review' then return new; end if;
    if tg_op = 'UPDATE' and old.review_version = new.review_version then return new; end if;
    organization_id_value := new.organization_id;
    kind_label := case when new.offer_type = 'gutschein' then 'Gutschein' else 'Aktion' end;
  else
    if new.moderation_status <> 'pending_review' then return new; end if;
    if tg_op = 'UPDATE' and old.review_version = new.review_version then return new; end if;
    organization_id_value := new.business_id;
    kind_label := 'Push-Nachricht';
  end if;

  select name into organization_name from public.organizations where id = organization_id_value;
  target_title := kind_label || ' wartet auf Freigabe';
  target_body := coalesce(organization_name, 'Ein Geschäft') || ' hat „' || new.title || '“ eingereicht.';

  insert into public.admin_notifications
    (recipient_user_id, organization_id, resource_type, resource_id, review_version, title, body, href)
  select pa.user_id, organization_id_value,
    case when tg_table_name = 'offers' then 'offer' else 'push_message' end,
    new.id, new.review_version, target_title, target_body, target_href
  from public.platform_admins pa
  where pa.is_active = true and pa.role in ('super_admin', 'operations')
  on conflict do nothing;
  return new;
end;
$$;

drop trigger if exists offers_queue_admin_review on public.offers;
create trigger offers_queue_admin_review after insert or update on public.offers
for each row execute function public.queue_marketing_admin_notifications();
drop trigger if exists push_messages_queue_admin_review on public.push_messages;
create trigger push_messages_queue_admin_review after insert or update on public.push_messages
for each row execute function public.queue_marketing_admin_notifications();

create or replace function public.enforce_offer_moderation()
returns trigger language plpgsql security definer set search_path = public as $$
declare is_admin boolean := public.is_platform_admin() or auth.role() = 'service_role';
begin
  if is_admin then return new; end if;
  if tg_op = 'INSERT' then
    new.requested_active := new.is_active;
    new.is_active := false;
    new.moderation_status := 'pending_review';
    new.submitted_by := auth.uid();
    new.submitted_at := now();
    new.reviewed_by := null; new.reviewed_at := null; new.rejection_reason := null;
    return new;
  end if;

  if row(new.title,new.description,new.offer_type,new.discount_type,new.discount_value,
         new.minimum_purchase_amount,new.redemption_code,new.conditions,new.media_asset_id,
         new.starts_at,new.ends_at,new.location_id)
     is distinct from
     row(old.title,old.description,old.offer_type,old.discount_type,old.discount_value,
         old.minimum_purchase_amount,old.redemption_code,old.conditions,old.media_asset_id,
         old.starts_at,old.ends_at,old.location_id) then
    new.requested_active := new.is_active or old.requested_active;
    new.is_active := false;
    new.moderation_status := 'pending_review';
    new.submitted_by := auth.uid();
    new.submitted_at := now();
    new.reviewed_by := null; new.reviewed_at := null; new.rejection_reason := null;
    new.review_version := old.review_version + 1;
  else
    new.moderation_status := old.moderation_status;
    new.reviewed_by := old.reviewed_by; new.reviewed_at := old.reviewed_at;
    new.rejection_reason := old.rejection_reason; new.review_version := old.review_version;
    if old.moderation_status <> 'approved' then new.is_active := false; end if;
  end if;
  return new;
end;
$$;

drop trigger if exists offers_enforce_moderation on public.offers;
create trigger offers_enforce_moderation before insert or update on public.offers
for each row execute function public.enforce_offer_moderation();

drop policy if exists "Public can read active offers" on public.offers;
create policy "Public can read approved active offers" on public.offers for select
to anon, authenticated using (
  moderation_status = 'approved' and is_active = true
  and (starts_at is null or starts_at <= now()) and (ends_at is null or ends_at >= now())
  and exists (select 1 from public.organizations o where o.id = organization_id and o.is_active and o.public_status = 'open')
  and (location_id is null or exists (select 1 from public.locations l where l.id = location_id and l.is_active and l.public_status in ('open','closed')))
);

